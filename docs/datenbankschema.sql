-- Von Hibernate aus den JPA-Entities erzeugtes Schema (H2).
-- Automatisch generiert beim Start der Anwendung; hier unveraendert uebernommen.

create table aufgabe (
    faellig_am date,
    bearbeiter_id bigint,
    erstellt_am timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    projekt_id bigint not null,
    titel varchar(160) not null,
    beschreibung varchar(2000),
    status varchar(20) not null,
    primary key (id)
);
create table benutzer (
    aktiv boolean not null,
    id bigint generated by default as identity,
    mandant_id bigint not null,
    nachname varchar(60) not null,
    vorname varchar(60) not null,
    passwort_hash varchar(100) not null,
    email varchar(160) not null,
    primary key (id),
    constraint uk_benutzer_mandant_email unique (mandant_id, email)
);
create table benutzer_rolle (
    benutzer_id bigint not null,
    rolle varchar(30) not null,
    primary key (benutzer_id, rolle)
);
create table mandant (
    aktiv boolean not null,
    id bigint generated by default as identity,
    kuerzel varchar(60) not null unique,
    name varchar(120) not null,
    primary key (id)
);
create table projekt (
    end_datum date,
    start_datum date,
    id bigint generated by default as identity,
    leiter_id bigint not null,
    mandant_id bigint not null,
    kunde varchar(120),
    name varchar(120) not null,
    beschreibung varchar(2000),
    status varchar(20) not null,
    primary key (id),
    constraint uk_projekt_mandant_name unique (mandant_id, name)
);
create table projekt_mitglied (
    benutzer_id bigint not null,
    projekt_id bigint not null,
    primary key (benutzer_id, projekt_id)
);
